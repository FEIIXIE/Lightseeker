using System;
using System.Collections.Generic;

namespace SeekerAutoChess.Prototype.Localization
{
    public enum GameLanguage
    {
        ChineseSimplified,
        English
    }

    /// <summary>
    /// Prototype string catalog kept outside the UI controller. New languages can be
    /// registered without changing gameplay, persistence, or battle code.
    /// </summary>
    public sealed class PrototypeLocalization
    {
        private readonly Dictionary<GameLanguage, Dictionary<string, string>> tables;

        private PrototypeLocalization(Dictionary<GameLanguage, Dictionary<string, string>> tables)
        {
            this.tables = tables ?? throw new ArgumentNullException(nameof(tables));
            ValidateTables();
        }

        public int LanguageCount { get { return tables.Count; } }

        public int TranslationCount
        {
            get { return tables[GameLanguage.English].Count; }
        }

        public string Translate(GameLanguage language, string key)
        {
            if (string.IsNullOrEmpty(key)) return string.Empty;
            Dictionary<string, string> table;
            if (!tables.TryGetValue(language, out table)) table = tables[GameLanguage.English];
            string value;
            return table.TryGetValue(key, out value) ? value : key;
        }

        public bool ContainsKey(GameLanguage language, string key)
        {
            Dictionary<string, string> table;
            return tables.TryGetValue(language, out table) && table.ContainsKey(key);
        }

        public static string GetLanguageCode(GameLanguage language)
        {
            return language == GameLanguage.ChineseSimplified ? "zh-Hans" : "en";
        }

        public static bool TryParseLanguageCode(string code, out GameLanguage language)
        {
            if (string.Equals(code, "zh-Hans", StringComparison.OrdinalIgnoreCase))
            {
                language = GameLanguage.ChineseSimplified;
                return true;
            }
            if (string.Equals(code, "en", StringComparison.OrdinalIgnoreCase))
            {
                language = GameLanguage.English;
                return true;
            }
            language = GameLanguage.English;
            return false;
        }

        public static PrototypeLocalization CreateDefault()
        {
            return new PrototypeLocalization(new Dictionary<GameLanguage, Dictionary<string, string>>
            {
                { GameLanguage.ChineseSimplified, CreateChineseSimplified() },
                { GameLanguage.English, CreateEnglish() }
            });
        }

        private void ValidateTables()
        {
            Dictionary<string, string> english;
            if (!tables.TryGetValue(GameLanguage.English, out english) || english.Count == 0)
            {
                throw new InvalidOperationException("English fallback localization is required.");
            }

            foreach (var languageTable in tables)
            {
                if (languageTable.Value == null)
                {
                    throw new InvalidOperationException("Localization table cannot be null: " + languageTable.Key);
                }
                if (languageTable.Value.Count != english.Count)
                {
                    throw new InvalidOperationException("Localization key count differs: " + languageTable.Key);
                }
                foreach (var key in english.Keys)
                {
                    if (!languageTable.Value.ContainsKey(key))
                    {
                        throw new InvalidOperationException("Missing localization key '" + key + "' in " + languageTable.Key);
                    }
                }
            }

        }

